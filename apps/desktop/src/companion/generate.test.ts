import { describe, expect, it } from "vitest";
import type { ActivityInfo } from "../activity/ActivityHost";
import {
  GENERATION_ENGINES,
  aiAccessibleName,
  aiLabel,
  aiTag,
  canGenerate,
  generationErrorText,
  generationPrefsOf,
  toGenerationError,
} from "./generate";

const set = (model: string | null, engine = "lullshift.quiz@1"): ActivityInfo => ({
  id: "lullshift.generated.quiz.abcdefghij12",
  name: "Rivers",
  description: "",
  category: "interactive",
  version: "0.1.0",
  storage: false,
  savedUtc: null,
  help: null,
  preview: false,
  playedSeconds: 0,
  engine,
  generated: { model, engine, createdUtc: "", topic: "", difficulty: "medium", unusable: false },
});

describe("the label", () => {
  it("names the model, or says 'your model' when it is unknown", () => {
    expect(aiLabel(set("gpt-test"))).toBe("AI-generated by gpt-test. It can be wrong.");
    expect(aiLabel(set(null))).toBe("AI-generated by your model. It can be wrong.");
    expect(aiLabel(set("  "))).toBe("AI-generated by your model. It can be wrong.");
  });

  it("cuts a long name to 40 characters", () => {
    expect(aiLabel(set("x".repeat(100)))).toBe(
      `AI-generated by ${"x".repeat(40)}. It can be wrong.`,
    );
  });

  it("adds the safety sentence for the three body engines only", () => {
    for (const [ref, e] of Object.entries(GENERATION_ENGINES)) {
      const text = aiLabel(set("m", ref))!;
      expect(text.includes("Stop if anything feels uncomfortable."), ref).toBe(e.body);
    }
  });

  it("is absent for anything that was not written by a model", () => {
    const plain = { ...set("m"), generated: null };
    expect(aiLabel(plain)).toBeNull();
    expect(aiTag(plain)).toBeNull();
    expect(aiAccessibleName(plain)).toBe("Rivers");
  });

  it("starts the accessible name with AI-generated, and tags with the model", () => {
    expect(aiAccessibleName(set("m"))).toMatch(/^AI-generated/);
    expect(aiTag(set("m"))).toBe("AI-generated · m");
    expect(aiTag(set(null))).toBe("AI-generated");
  });
});

describe("the switches", () => {
  it("read as off for an older core, and body never stands without the first", () => {
    expect(generationPrefsOf({ toolsEnabled: false })).toEqual({
      enabled: false,
      bodyEnabled: false,
    });
    expect(generationPrefsOf(null)).toEqual({ enabled: false, bodyEnabled: false });
    expect(generationPrefsOf({ contentGeneration: { enabled: false, bodyEnabled: true } })).toEqual(
      { enabled: false, bodyEnabled: false },
    );
    expect(generationPrefsOf({ contentGeneration: { enabled: true, bodyEnabled: true } })).toEqual({
      enabled: true,
      bodyEnabled: true,
    });
  });

  it("allow the eight engines, body ones only with the second switch", () => {
    const on = { enabled: true, bodyEnabled: false };
    expect(canGenerate("lullshift.quiz@1", on)).toBe(true);
    expect(canGenerate("lullshift.movement@1", on)).toBe(false);
    expect(canGenerate("lullshift.movement@1", { enabled: true, bodyEnabled: true })).toBe(true);
    expect(canGenerate("lullshift.away@1", { enabled: true, bodyEnabled: true })).toBe(false);
    expect(canGenerate("lullshift.toy@1", { enabled: true, bodyEnabled: true })).toBe(false);
    expect(canGenerate("com.example.engine@1", { enabled: true, bodyEnabled: true })).toBe(false);
    expect(canGenerate(null, { enabled: true, bodyEnabled: true })).toBe(false);
    expect(canGenerate("lullshift.quiz@1", { enabled: false, bodyEnabled: false })).toBe(false);
  });
});

describe("errors", () => {
  it("reduce to a kind and the backend's fixed sentence", () => {
    expect(toGenerationError({ kind: "didNotFit", message: "m", providerReason: null })).toEqual({
      kind: "didNotFit",
      message: "m",
    });
    expect(toGenerationError("command generate_set not found").kind).toBe("unavailable");
    expect(toGenerationError(new Error("secret topic text")).kind).toBe("internal");
    expect(JSON.stringify(toGenerationError(new Error("secret topic text")))).not.toContain(
      "secret",
    );
  });

  it("keeps the provider's words apart and cut", () => {
    const e = toGenerationError({
      kind: "provider",
      message: "m",
      providerReason: { speaker: "The provider", text: "x".repeat(500) },
    });
    expect(e.providerReason?.text.length).toBe(300);
  });

  it("are honest and calm for each kind", () => {
    const text = (kind: string) => generationErrorText({ kind, message: "" }, "localhost:11434");
    expect(text("didNotFit")).toBe(
      "Your model's set didn't fit this activity, so Lullshift didn't start it. Nothing was lost.",
    );
    expect(text("offline")).toContain("Can't reach localhost:11434");
    expect(text("noKey")).toContain("No key is set");
    expect(text("keyRejected")).toContain("rejected the key");
    expect(text("timeout")).toContain("took too long");
    expect(text("rateLimited")).toContain("limiting requests");
    expect(text("provider")).toContain("had a problem");
    expect(text("budgetRefused")).toContain("budget");
    expect(text("budgetReached")).toContain("budget");
    expect(text("cancelled")).toContain("Cancelled");
    expect(text("somethingNew")).toContain("Something went wrong inside Lullshift");
    expect(generationErrorText({ kind: "generationOff", message: "It is off." })).toBe(
      "It is off.",
    );
  });
});
